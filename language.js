    const normalizedFrenchToEnglish = new Map();
    const englishToFrench = new Map();
    Object.entries(frenchToEnglish).forEach(([french, english]) => {
        normalizedFrenchToEnglish.set(normalize(french), english);
        if (!englishToFrench.has(normalize(english))) englishToFrench.set(normalize(english), french);
    });

    function normalize(value) {
        return value.replace(/\s+/g, " ").trim();
    }

    function translateValue(value, language) {
        const normalized = normalize(value);
        const translated = language === "en"
            ? normalizedFrenchToEnglish.get(normalized)
            : englishToFrench.get(normalized);
        if (!translated) return value;
        const leading = value.match(/^\s*/)?.[0] || "";
        const trailing = value.match(/\s*$/)?.[0] || "";
        return `${leading}${translated}${trailing}`;
    }

    window.portfolioTranslate = (value, language = document.documentElement.lang) =>
        translateValue(value, language === "en" ? "en" : "fr");

    function applyLanguage(language) {
        const selectedLanguage = language === "en" ? "en" : "fr";
        document.documentElement.lang = selectedLanguage;

        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
            acceptNode(node) {
                const parent = node.parentElement;
                if (!parent || parent.closest("script, style, noscript")) return NodeFilter.FILTER_REJECT;
                return NodeFilter.FILTER_ACCEPT;
            }
        });

        let textNode;
        while ((textNode = walker.nextNode())) {
            textNode.nodeValue = translateValue(textNode.nodeValue || "", selectedLanguage);
        }

        document.querySelectorAll("[data-language-fr][data-language-en]").forEach(element => {
            element.textContent = element.getAttribute(`data-language-${selectedLanguage}`) || "";
        });

        document.querySelectorAll("input[placeholder], textarea[placeholder], [aria-label], [title], img[alt]").forEach(element => {
            ["placeholder", "aria-label", "title", "alt"].forEach(attribute => {
                if (element.hasAttribute(attribute)) {
                    element.setAttribute(attribute, translateValue(element.getAttribute(attribute) || "", selectedLanguage));
                }
            });
        });

        document.querySelectorAll('meta[name="description"], meta[property^="og:"], meta[property^="twitter:"], meta[name^="twitter:"]').forEach(meta => {
            meta.content = translateValue(meta.content, selectedLanguage);
        });
        document.title = translateValue(document.title, selectedLanguage);

        document.querySelectorAll(".lang-btn").forEach(button => {
            const active = button.dataset.lang === selectedLanguage;
            button.setAttribute("aria-pressed", String(active));
            button.classList.toggle("bg-blue-600", active);
            button.classList.toggle("bg-gray-700", !active);
        });

        window.dispatchEvent(new CustomEvent("portfolio:languagechange", {
            detail: { language: selectedLanguage }
        }));
    }

    function initializeLanguageSwitcher() {
        let savedLanguage = "fr";
        try {
            savedLanguage = localStorage.getItem("language") === "en" ? "en" : "fr";
        } catch (error) {
            console.warn("Language preference could not be read:", error);
        }

        applyLanguage(savedLanguage);
        document.querySelectorAll(".lang-btn").forEach(button => {
            button.addEventListener("click", () => {
                const language = button.dataset.lang === "en" ? "en" : "fr";
                try {
                    localStorage.setItem("language", language);
                } catch (error) {
                    console.warn("Language preference could not be saved:", error);
                }
                applyLanguage(language);
            });
        });
    }

    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", initializeLanguageSwitcher, { once: true });
    } else {
        initializeLanguageSwitcher();
    }
